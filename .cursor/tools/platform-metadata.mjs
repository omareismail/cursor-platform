#!/usr/bin/env node
/**
 * platform-metadata.mjs — one computed source of truth for "how big is this platform".
 *
 * WHY THIS EXISTS
 *
 * The counts "96 skills, 14 subagents, 12 rules" were written by hand in eleven
 * places. Every one of them was correct on the day it was typed, and every one
 * of them drifts the moment a skill is added. `docs-lint` catches the drift in
 * markdown - but `.claude-plugin/plugin.json` sat at "77 skills, 8 subagents,
 * 5 enforcement hooks" for exactly as long as nobody read it, because it is JSON
 * and the markdown linter never opened it.
 *
 * A platform whose whole thesis is "generated, not asserted" should not assert
 * its own size. This computes it, writes it once, and fails CI when any document
 * disagrees with reality - markdown and JSON alike.
 *
 * Usage:
 *   node .cursor/tools/platform-metadata.mjs show            # the computed truth
 *   node .cursor/tools/platform-metadata.mjs write           # -> platform-metadata.json
 *   node .cursor/tools/platform-metadata.mjs check [--fix]   # find (and optionally repair) drift
 *
 * Exit codes:  0 = in sync   1 = drift found   2 = usage
 */

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { execFileSync } from "node:child_process";

const ROOT = process.env.CLAUDE_PROJECT_DIR || repoRoot() || process.cwd();

function repoRoot() {
  try {
    return execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch { return null; }
}

const dirs = (p) => { try { return readdirSync(join(ROOT, p), { withFileTypes: true }).filter(d => d.isDirectory()).length; } catch { return 0; } };
const files = (p, ext, exclude = []) => {
  try { return readdirSync(join(ROOT, p)).filter(f => f.endsWith(ext) && !exclude.includes(f)).length; } catch { return 0; }
};

/* --------------------------------------------------------------- the truth */

/**
 * `_lib.mjs` is a helper and `sync-skills.mjs` is a generator - neither is a
 * hook, and counting them is how "6 enforcement hooks" becomes "8" in a doc
 * nobody meant to change. `build-plugin.mjs` is a builder, not a validator,
 * which is why tools and validators are separate numbers rather than one.
 */
export function metadata() {
  const NOT_HOOKS = ["_lib.mjs", "sync-skills.mjs"];
  return {
    "//": "GENERATED by .cursor/tools/platform-metadata.mjs. Do not hand-edit. Every count in the docs is checked against this.",
    generatedAt: new Date().toISOString(),
    version: pluginVersion(),
    counts: {
      skills: dirs(".cursor/skills"),
      agents: files(".claude/agents", ".md"),
      rules: files(".cursor/rules", ".mdc"),
      hooks: files(".claude/hooks", ".mjs", NOT_HOOKS),
      tools: files(".cursor/tools", ".mjs"),
      validators: files(".cursor/tools", ".mjs", ["build-plugin.mjs"]),
      gates: files(".cursor/lifecycle/gates", ".md"),
      memoryBank: files("memory-bank", ".md"),
      phases: 6,
    },
  };
}

function pluginVersion() {
  try { return JSON.parse(readFileSync(join(ROOT, ".claude-plugin", "plugin.json"), "utf8")).version || "0.0.0"; }
  catch { return "0.0.0"; }
}

/* ------------------------------------------------------------ drift finding */

/**
 * Nouns that name a count, mapped to the key that holds the real number.
 * Optional qualifiers ("read-only", "enforcement", "guard") sit between the
 * number and the noun and must not break the match - that is precisely how the
 * plugin manifest's "8 read-only subagents" escaped the markdown linter's
 * simpler "N skills" pattern.
 */
const NOUNS = {
  skills: "skills", skill: "skills",
  subagents: "agents", subagent: "agents", agents: "agents",
  rules: "rules", rule: "rules",
  hooks: "hooks", hook: "hooks",
  validators: "validators", validator: "validators",
  gates: "gates", gate: "gates",
};
/**
 * Up to two words may sit between the number and the noun: "8 read-only
 * subagents", "77 slash-command skills", "11 .mdc guard rules". A closed list of
 * adjectives missed every one it had not been told about, which is the same
 * hand-maintained-list failure this tool exists to catch. The strict scan reads
 * only manifest files, where a bare number can only be the total, so a wildcard
 * costs nothing there; the --all sweep is advisory and rewrites nothing.
 */
const QUALIFIER = "(?:[\\w.-]+ ){0,2}";
const PATTERN = new RegExp(`\\b(\\d{1,3}) ${QUALIFIER}(${Object.keys(NOUNS).join("|")})\\b`, "gi");

/** Point-in-time records. Their numbers are history, not claims about now. */
const HISTORICAL = /(ENTERPRISE_MATURITY_REPORT|GOVERNANCE_REPORT|MIGRATION_NOTES|PHASE\d|PROPOSAL-REVIEW)/i;
/** Regenerated from source. Fixing the output instead of the generator is a trap. */
const GENERATED = /^(\.claude\/skills|plugin|plugin\.__check__|node_modules|\.git)\//;
/** A separate platform with its own, smaller numbers. */
const FOREIGN = /^flutter-platform\//;

/**
 * Strict scope: the files that speak for the platform as a whole. A bare
 * "12 rules" here can only mean the total, so drift is unambiguous and --fix is
 * safe.
 *
 * Everywhere else, prose legitimately counts subsets ("12 skills total - the
 * generators wired to pattern-finder") and cites rules by number ("09 and 10
 * guard rules"), both of which look identical to a total. Rewriting those would
 * corrupt correct documentation to satisfy a linter - so the wide sweep is
 * advisory only, behind --all, and never rewrites anything.
 */
const MANIFESTS = new Set([
  ".claude-plugin/plugin.json",
  ".claude-plugin/marketplace.json",
  "README.md",
  "AGENTS.md",
  "CLAUDE.md",
  "HANDBOOK.md",
  "HANDBOOK.ar.md",
  "templates/README.md",
  ".cursor/docs/START-HERE.md",
  ".cursor/docs/NEW-PROJECT.md",
  ".cursor/docs/APPLY-TO-PROJECT.md",
  ".cursor/docs/skill-catalog.md",
  ".cursor/docs/DUAL-AGENT-SETUP.md",
  // Not manifests, but they make live claims about the platform's size in prose:
  // "96 skills of throughput amplification", "all 96 skills correctly cased".
  // docs-lint caught these and this tool did not, which is a gap in the list,
  // not in the pattern - so the list grew.
  ".cursor/docs/PROPOSAL-REVIEW.md",
  ".cursor/skills/delivery-metrics/skill.md",
  ".cursor/skills/platform-health-validator/skill.md",
]);

function walk(dir, out = []) {
  let entries;
  try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    const abs = join(dir, e.name);
    const rel = relative(ROOT, abs).split("\\").join("/");
    if (GENERATED.test(rel + "/") || FOREIGN.test(rel + "/")) continue;
    if (e.isDirectory()) { if (!e.name.startsWith(".git")) walk(abs, out); continue; }
    if (/\.(md|json)$/.test(e.name) && !HISTORICAL.test(rel)) out.push(rel);
  }
  return out;
}

function findDrift(truth, { all = false } = {}) {
  const drift = [];
  for (const rel of walk(ROOT)) {
    if (!all && !MANIFESTS.has(rel)) continue;
    // The metadata file states the truth; it cannot disagree with itself.
    if (rel === "platform-metadata.json") continue;
    let body;
    try { body = readFileSync(join(ROOT, rel), "utf8"); } catch { continue; }
    body.split("\n").forEach((line, i) => {
      // A wide qualifier catches adjectives nobody listed, and with it the
      // occasional line that legitimately counts something else - a frozen
      // historical figure, a proposal's own total. `count-ok` is the explicit
      // way to say "this number is not a claim about the platform's size".
      if (line.includes("count-ok")) return;
      for (const m of line.matchAll(PATTERN)) {
        const key = NOUNS[m[2].toLowerCase()];
        const stated = Number(m[1]);
        const actual = truth.counts[key];
        if (actual === undefined || stated === actual) continue;
        drift.push({ file: rel, line: i + 1, text: m[0], stated, actual, key, replacement: m[0].replace(/^\d+/, String(actual)) });
      }
    });
  }
  return drift;
}

/* ------------------------------------------------------------------ commands */

const [cmd, ...args] = process.argv.slice(2);
const truth = metadata();

if (cmd === "show") {
  console.log(JSON.stringify(truth, null, 2));
} else if (cmd === "write") {
  writeFileSync(join(ROOT, "platform-metadata.json"), JSON.stringify(truth, null, 2) + "\n", "utf8");
  console.log("platform-metadata.json written:");
  for (const [k, v] of Object.entries(truth.counts)) console.log(`  ${k.padEnd(12)} ${v}`);
} else if (cmd === "check") {
  const all = args.includes("--all");
  const fix = args.includes("--fix");
  if (all && fix) {
    console.error("--all is advisory and never rewrites. Prose counts subsets legitimately; a blind rewrite there corrupts correct docs.");
    process.exit(2);
  }
  const drift = findDrift(truth, { all });
  if (!drift.length) {
    const scope = all ? "every .md and .json" : `${MANIFESTS.size} manifest files`;
    console.log(`Counts in sync across ${scope} (${Object.entries(truth.counts).map(([k, v]) => `${v} ${k}`).join(", ")}).`);
    process.exit(0);
  }
  console.log(`${drift.length} stale count${drift.length > 1 ? "s" : ""}:\n`);
  const byFile = {};
  for (const d of drift) (byFile[d.file] ||= []).push(d);
  for (const [file, ds] of Object.entries(byFile)) {
    console.log(`  ${file}`);
    for (const d of ds) console.log(`    line ${d.line}: "${d.text}" - actual is ${d.actual}`);
    if (fix) {
      let body = readFileSync(join(ROOT, file), "utf8");
      for (const d of ds) body = body.split(d.text).join(d.replacement);
      writeFileSync(join(ROOT, file), body, "utf8");
      console.log(`    FIXED`);
    }
  }
  if (all) {
    console.log(`\nADVISORY. This sweep reads prose, where a number may name a subset`);
    console.log(`("12 skills total") or cite a rule by number ("09 and 10 guard rules").`);
    console.log(`Review each by hand; nothing was rewritten.`);
    process.exit(0);
  }
  if (!fix) {
    console.log(`\nRe-run with --fix to repair, or correct them by hand.`);
    console.log(`A count written by hand drifts the day someone adds a skill. Prefer generating it.`);
  }
  process.exit(fix ? 0 : 1);
} else {
  console.error(`platform-metadata.mjs — computed source of truth for the platform's size

  show             print the computed counts
  write            write platform-metadata.json
  check [--fix]    find (and optionally repair) stale counts in .md and .json
                   (a line containing count-ok is skipped)

Checks markdown AND json. docs-lint only reads markdown, which is how
.claude-plugin/plugin.json kept claiming 77 skills.`);
  process.exit(2);
}
